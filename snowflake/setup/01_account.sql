-- One-time account setup. Run as SYSADMIN / SECURITYADMIN.
-- Separate roles for loading (Snowpipe), transforming (tasks) and reading (BI).

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOANS_LOADER;
CREATE ROLE IF NOT EXISTS LOANS_TRANSFORMER;
CREATE ROLE IF NOT EXISTS LOANS_READER;
GRANT ROLE LOANS_LOADER      TO ROLE SYSADMIN;
GRANT ROLE LOANS_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE LOANS_READER      TO ROLE LOANS_TRANSFORMER;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Fallback for tasks that outgrow serverless compute';

CREATE DATABASE IF NOT EXISTS LOANS;
CREATE SCHEMA IF NOT EXISTS LOANS.RAW;
CREATE SCHEMA IF NOT EXISTS LOANS.CORE;
CREATE SCHEMA IF NOT EXISTS LOANS.MART;

GRANT USAGE ON DATABASE LOANS TO ROLE LOANS_LOADER;
GRANT USAGE ON DATABASE LOANS TO ROLE LOANS_TRANSFORMER;
GRANT USAGE ON DATABASE LOANS TO ROLE LOANS_READER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE, CREATE FILE FORMAT ON SCHEMA LOANS.RAW TO ROLE LOANS_LOADER;
GRANT USAGE, CREATE TABLE, CREATE STREAM, CREATE TASK ON SCHEMA LOANS.RAW  TO ROLE LOANS_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE STREAM, CREATE TASK ON SCHEMA LOANS.CORE TO ROLE LOANS_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE STREAM, CREATE TASK ON SCHEMA LOANS.MART TO ROLE LOANS_TRANSFORMER;
GRANT USAGE ON SCHEMA LOANS.MART TO ROLE LOANS_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LOANS.MART TO ROLE LOANS_READER;

USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE LOANS_TRANSFORMER;

-- Cap spend: notify at 80%, suspend at 100% of the monthly quota.
CREATE RESOURCE MONITOR IF NOT EXISTS LOANS_MONTHLY
  WITH CREDIT_QUOTA = 50 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE TRANSFORM_WH SET RESOURCE_MONITOR = LOANS_MONTHLY;
